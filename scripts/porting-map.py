#!/usr/bin/env python3
"""Generate PORTING.md: oracle symbol -> TS symbol, and inventory row -> TS file:line.

Nothing in the document is written by hand. A ported module is one listed in
PORTED; its public oracle symbols must exist under the same name in the TS
module, or this script fails. Inventory rows are found through the
`// row N <mutant id>: ... <module>.py:L` comments above the TS guards.
`--check` fails when PORTING.md is not what this script would write.
"""
import ast, re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
PORTED = {'connectome_errors': 'src/errors.ts', 'connectome_lock': 'src/lock.ts', 'connectome_inputs': 'src/inputs.ts'}
# The three names lock.py imports lazily from the archive module; the module itself is not ported.
SEAM = {'connectome_archive': ('src/archive.ts', {'npm_name', 'validate_dependency_record', 'check_dependencies'})}
# Module-private TS declarations that hold the body of a public oracle function.
OWNER = {'mapLock': 'map_lock', 'namesOnly': 'names_only', 'credentialShaped': 'credential_shaped', 'TOKEN_SHAPES': 'credential_shaped',
         'ASSIGNMENT': 'credential_shaped', 'URL_SHAPES': 'credential_shaped', 'STORE_PATH': 'credential_shaped', 'CREDENTIAL_SHAPES': 'credential_shaped',
         'BOUNDARY': 'credential_shaped', 'LETTER': 'credential_shaped', 'insensitive': 'credential_shaped',
         'MESSAGES': 'diagnostic', 'COOK_CODES': 'cook_code', 'CODE': 'cook_code'}
# Rows whose guarantee is only partly inside the ported modules: what is still owed, and by whom.
PARTIAL = {
    1: 'callers in cook.ts and archive.ts are not ported',
    3: 'the caller in cook.ts is not ported',
    7: 'the envelope parser stays in src/pylike/json.ts; these are the lock and recipe readers',
    9: 'archive.ts (next slice) owns the other half; src/archive.ts is a stub of the seam',
    11: None, 23: 'the staged copy in deploy.ts is not ported',
    28: 'deploy.ts, cook.ts and io/proc.ts are not ported',
    49: 'only the .file-env check; catalog.ts, deploy.ts and cook.ts own the others',
}
MARKER = re.compile(r'^\s*// row (\d+) ([^:]+): (.*) (lock|inputs|errors)\.py:(\d+)(?:-(\d+))?$')
DECLARATION = re.compile(r'^(?:export )?(?:function|class|const|interface) (\w+)')
EXPORT = re.compile(r'^export (?:function|class|const) (\w+)')


def scan(relative):
    """(exports: name -> line, markers: [(row, id, text, oracle range, line, enclosing declaration)])."""
    exports, markers, enclosing = {}, [], None
    module = Path(relative).stem
    source = (ROOT / relative).read_text().split('\n')
    for number, line in enumerate(source, 1):
        declared = DECLARATION.match(line)
        if declared:
            enclosing = declared[1]
        exported = EXPORT.match(line)
        if exported:
            exports[exported[1]] = number
        marker = MARKER.match(line)
        if marker:
            if marker[4] != module:
                raise ValueError('%s:%d cites another module' % (relative, number))
            # A comment directly above a top-level declaration belongs to that declaration.
            follow = next(text for text in source[number:] if not text.lstrip().startswith('//'))
            holder = DECLARATION.match(follow)[1] if DECLARATION.match(follow) else enclosing
            markers.append((int(marker[1]), marker[2], marker[3].rstrip('. '), marker[4] + '.py:' + marker[5] + ('-' + marker[6] if marker[6] else ''), number, OWNER.get(holder, holder)))
    return exports, markers


def render():
    scanned = {module: scan(relative) for module, relative in PORTED.items()}
    seams = {module: scan(relative)[0] for module, (relative, _names) in SEAM.items()}
    lines = ['# Porting map — baseline a49b5dc', '',
             'Generated by `scripts/porting-map.py`; `--check` runs in the unit suite. Do not edit by hand.', '',
             'Ported to strict TypeScript: `errors`, `lock`, `inputs` (plan section 3.1, modules 1–3). Each public oracle',
             'symbol of a ported module has a TS export of the same name; "Rows" are the fail-closed inventory rows',
             '(plan section 4.1) whose guards sit in that function. `archive` is not ported: `src/archive.ts` is a stub',
             'of the three names `lock.py` imports lazily, and says so in its header. Every other symbol is oracle-only.', '',
             '## Symbols', '',
             '| Status | Symbol | Frozen source | TypeScript | Rows |', '| --- | --- | --- | --- | --- |']
    for path in sorted((ROOT / 'oracle/module_utils').rglob('*.py')):
        tree = ast.parse(path.read_text())
        for node in tree.body:
            if not isinstance(node, (ast.FunctionDef, ast.ClassDef)) or node.name.startswith('_'):
                continue
            source = '`' + path.relative_to(ROOT).as_posix() + ':' + str(node.lineno) + '`'
            symbol = '`' + path.stem + '.' + node.name + '`'
            if path.stem in PORTED:
                exports, markers = scanned[path.stem]
                if node.name not in exports:
                    raise ValueError('ported module lacks ' + path.stem + '.' + node.name)
                rows = sorted({row for row, _id, _text, _range, _line, owner in markers if owner == node.name})
                lines.append('| ported | %s | %s | `%s:%d` | %s |' % (symbol, source, PORTED[path.stem], exports[node.name], ', '.join(map(str, rows))))
            elif path.stem in SEAM and node.name in SEAM[path.stem][1]:
                lines.append('| oracle-only; stub of the lazy seam | %s | %s | `%s:%d` | |' % (symbol, source, SEAM[path.stem][0], seams[path.stem][node.name]))
            else:
                lines.append('| oracle-only | %s | %s | | |' % (symbol, source))
    owned = sorted({(row, owner) for _exports, markers in scanned.values() for row, _id, _text, _range, _line, owner in markers})
    unowned = [entry for entry in owned if not any(entry[1] in exports for exports, _markers in scanned.values())]
    if unowned:
        raise ValueError('row marker outside a public function: %r' % unowned)
    lines += ['', '## Inventory rows in the ported modules', '',
              'One line per guard site. "Ported" means the guard exists in TS at that line, has a TS mutant',
              '(`test/mutants/ts-anchors.golden`) and is exercised by oracle-written vectors. A row marked partial is',
              'shared with modules that are not ported yet; only the sites listed here are done.', '',
              '| Row | Mutant id | Status | TypeScript | Oracle | Check |', '| --- | --- | --- | --- | --- | --- |']
    sites = sorted((row, PORTED[module], line, ident, text, cited) for module, (_exports, markers) in scanned.items() for row, ident, text, cited, line, _owner in markers)
    for row, relative, line, ident, text, cited in sites:
        status = 'ported (row partial: ' + PARTIAL[row] + ')' if PARTIAL.get(row) else 'ported'
        lines.append('| %d | `%s` | %s | `%s:%d` | `%s` | %s |' % (row, ident, status, relative, line, cited, text))
    rows = sorted({site[0] for site in sites})
    lines += ['', 'Rows with at least one ported site: ' + ', '.join(map(str, rows)) + '.', '']
    return '\n'.join(lines)


def main():
    text = render()
    target = ROOT / 'PORTING.md'
    if '--check' in sys.argv[1:]:
        if target.read_text() != text:
            print('BLOCKED: PORTING.md is stale; run scripts/porting-map.py')
            return 1
        return 0
    target.write_text(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
